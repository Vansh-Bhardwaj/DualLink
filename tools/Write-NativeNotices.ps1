[CmdletBinding()]
param(
    # Where the SPDX software bill of materials is written.
    [Parameter(Mandatory)] [string]$SbomPath,
    [Parameter(Mandatory)] [string]$Version
)

# Lists every Rust crate built into DualLink 5: rewrites the generated part of
# THIRD-PARTY-NOTICES.md and writes an SPDX 2.3 JSON bill of materials.

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$metadata = cargo metadata --format-version 1 --locked --filter-platform x86_64-pc-windows-msvc --manifest-path (Join-Path $repoRoot 'Cargo.toml') | ConvertFrom-Json
if ($LASTEXITCODE -ne 0) { throw 'cargo metadata failed.' }

# Only crates that are built into the shipped programs: follow the dependency graph from the
# app and the service, leaving out build-only and test-only dependencies.
$nodes = @{}
foreach ($node in $metadata.resolve.nodes) { $nodes[$node.id] = $node }
$roots = $metadata.packages | Where-Object { $_.name -in 'duallink-app', 'duallink-service' } | ForEach-Object { $_.id }
$seen = New-Object 'System.Collections.Generic.HashSet[string]'
$queue = New-Object 'System.Collections.Generic.Queue[string]'
foreach ($root in $roots) { [void]$seen.Add($root); $queue.Enqueue($root) }
while ($queue.Count -gt 0) {
    foreach ($dep in $nodes[$queue.Dequeue()].deps) {
        $normal = $dep.dep_kinds | Where-Object { $null -eq $_.kind }
        if ($normal -and $seen.Add($dep.pkg)) { $queue.Enqueue($dep.pkg) }
    }
}
$packages = $metadata.packages |
    Where-Object { $seen.Contains($_.id) -and $_.name -notlike 'duallink-*' } |
    Sort-Object name, version

$rows = foreach ($p in $packages) {
    $license = if ($p.license) { $p.license } elseif ($p.license_file) { "see $($p.license_file)" } else { 'not stated' }
    $source = if ($p.repository) { $p.repository } else { "https://crates.io/crates/$($p.name)" }
    "| $($p.name) | $($p.version) | $license | $source |"
}
$generated = @(
    '<!-- Generated by tools/Write-NativeNotices.ps1; edit the script, not this section. -->',
    '',
    "DualLink $Version is built from $($packages.Count) Rust crates. Each is used unmodified under the license its authors chose:",
    '',
    '| Crate | Version | License | Source |',
    '|---|---|---|---|'
) + $rows
$notices = Join-Path $repoRoot 'THIRD-PARTY-NOTICES.md'
$text = Get-Content -LiteralPath $notices -Raw
$marker = '## Rust crates'
$at = $text.IndexOf($marker)
if ($at -lt 0) { throw "THIRD-PARTY-NOTICES.md has no '$marker' section." }
$text = $text.Substring(0, $at) + $marker + "`n`n" + ($generated -join "`n") + "`n"
Set-Content -LiteralPath $notices -Value $text -Encoding utf8 -NoNewline

$spdxPackages = @([ordered]@{
    SPDXID = 'SPDXRef-DualLink'; name = 'DualLink'; versionInfo = $Version
    downloadLocation = 'https://github.com/Vansh-Bhardwaj/DualLink'; licenseConcluded = 'AGPL-3.0-only'
    licenseDeclared = 'AGPL-3.0-only'; copyrightText = 'NOASSERTION'; supplier = 'NOASSERTION'
})
$relationships = @([ordered]@{ spdxElementId = 'SPDXRef-DOCUMENT'; relationshipType = 'DESCRIBES'; relatedSpdxElement = 'SPDXRef-DualLink' })
$index = 0
foreach ($p in $packages) {
    $index++
    $id = "SPDXRef-Crate-$index"
    $declared = if ($p.license) { ($p.license -replace '/', ' OR ') } else { 'NOASSERTION' }
    $spdxPackages += [ordered]@{
        SPDXID = $id; name = $p.name; versionInfo = $p.version
        downloadLocation = "https://crates.io/crates/$($p.name)/$($p.version)"; licenseConcluded = 'NOASSERTION'
        licenseDeclared = $declared; copyrightText = 'NOASSERTION'; supplier = 'NOASSERTION'
        externalRefs = @([ordered]@{ referenceCategory = 'PACKAGE-MANAGER'; referenceType = 'purl'; referenceLocator = "pkg:cargo/$($p.name)@$($p.version)" })
    }
    $relationships += [ordered]@{ spdxElementId = 'SPDXRef-DualLink'; relationshipType = 'DEPENDS_ON'; relatedSpdxElement = $id }
}
$sbom = [ordered]@{
    spdxVersion = 'SPDX-2.3'; dataLicense = 'CC0-1.0'; SPDXID = 'SPDXRef-DOCUMENT'; name = "DualLink $Version"
    documentNamespace = "https://github.com/Vansh-Bhardwaj/DualLink/spdx/$Version"
    creationInfo = [ordered]@{ created = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ'); creators = @('Tool: tools/Write-NativeNotices.ps1') }
    packages = $spdxPackages; relationships = $relationships
}
$sbom | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath $SbomPath -Encoding utf8
Write-Host "Listed $($packages.Count) crates."
